# Generates julia/Godot/src/generated/layout.jl and method_hashes.tsv from extension_api.json.

"Non-math builtins that Julia treats as opaque, ABI-sized values (math types are hand-written in phase 05)."
const OPAQUE_BUILTINS = ["String", "StringName", "NodePath", "RID", "Callable", "Signal", "Dictionary", "Array",
                         "PackedByteArray", "PackedInt32Array", "PackedInt64Array", "PackedFloat32Array",
                         "PackedFloat64Array", "PackedStringArray", "PackedVector2Array", "PackedVector3Array",
                         "PackedColorArray", "PackedVector4Array"]

build_configuration(precision::AbstractString) =
    (precision == "double" ? "double_" : "float_") * string(Sys.WORD_SIZE)

"Map builtin class names (e.g. `Transform2D`) to their `GDEXTENSION_VARIANT_TYPE_*` constant names."
function variant_type_constants(iface)
    enum = only(filter(t -> t["name"] == "GDExtensionVariantType", iface["types"]))
    prefix = "GDEXTENSION_VARIANT_TYPE_"
    return Dict(lowercase(replace(v["name"][(length(prefix) + 1):end], "_" => "")) => v["name"] for v in enum["values"])
end

function variant_type_constant(consts, builtin::AbstractString)
    key = lowercase(builtin)
    haskey(consts, key) || error("no variant type for builtin $builtin")
    return consts[key]
end

function find_configuration(entries, config)
    idx = findfirst(e -> e["build_configuration"] == config, entries)
    idx === nothing && error("build configuration $config not found in extension_api.json")
    return entries[idx]
end

function generate_layout(io::IO, api, iface; precision::AbstractString = "single")
    config = build_configuration(precision)
    sizes = Dict(s["name"] => s["size"] for s in find_configuration(api["builtin_class_sizes"], config)["sizes"])
    offsets = find_configuration(api["builtin_class_member_offsets"], config)["classes"]
    consts = variant_type_constants(iface)
    builtins = Dict(b["name"] => b for b in api["builtin_classes"])
    header = api["header"]

    println(io, "# GENERATED by GodotBindgen from extension_api.json ($(header["version_full_name"])). Do not edit.\n")
    println(io, "const BUILD_CONFIGURATION = $(repr(config))")
    println(io, "const real_t = $(precision == "double" ? "Float64" : "Float32")")
    println(io, "const API_VERSION = v\"$(header["version_major"]).$(header["version_minor"]).$(header["version_patch"])\"\n")

    println(io, "const BUILTIN_SIZES = Dict{String, Int}(")
    for (name, size) in sort!(collect(sizes))
        println(io, "    $(repr(name)) => $size,")
    end
    println(io, ")\n")

    println(io, "\"Member layout `(member, offset, meta)` of builtin structs for the active build configuration.\"")
    println(io, "const MEMBER_OFFSETS = Dict{String, Vector{Tuple{String, Int, String}}}(")
    for cls in offsets
        members = join(["($(repr(m["member"])), $(m["offset"]), $(repr(m["meta"])))" for m in cls["members"]], ", ")
        println(io, "    $(repr(cls["name"])) => [$members],")
    end
    println(io, ")\n")

    println(io, "\"Variant type of every builtin class, by Godot name.\"")
    println(io, "const BUILTIN_VARIANT_TYPES = Dict{String, Int32}(")
    for b in api["builtin_classes"]
        println(io, "    $(repr(b["name"])) => $(variant_type_constant(consts, b["name"])),")
    end
    println(io, ")\n")

    words(n) = (n % 8 == 0 || error("size $n is not a multiple of 8"); n ÷ 8)
    println(io, "\"Opaque, ABI-sized Variant. Ownership: whoever constructs it must `destroy!` it exactly once.\"")
    println(io, "struct RawVariant\n    _data::NTuple{$(words(sizes["Variant"])), UInt64}\nend\n")
    for name in OPAQUE_BUILTINS
        println(io, "\"Opaque, ABI-sized Godot `$name`. Ownership: whoever constructs it must `destroy!` it exactly once.\"")
        println(io, "struct Raw$name <: RawBuiltin\n    _data::NTuple{$(words(sizes[name])), UInt64}\nend\n")
    end
    for name in OPAQUE_BUILTINS
        b = builtins[name]
        raw = "Raw$name"
        println(io, "variant_type(::Type{$raw}) = $(variant_type_constant(consts, name))")
        println(io, "has_destructor(::Type{$raw}) = $(b["has_destructor"])")
        for ctor in b["constructors"]
            args = get(ctor, "arguments", [])
            length(args) == 1 || continue
            from = args[1]["type"]
            from in OPAQUE_BUILTINS || continue
            println(io, "constructor_index(::Type{$raw}, ::Type{Raw$from}) = Int32($(ctor["index"]))")
        end
        println(io)
    end
    println(io, "const RAW_BUILTINS = ($(join(("Raw" * n for n in OPAQUE_BUILTINS), ", ")),)")
    return nothing
end

"One line per method: `kind<TAB>owner<TAB>name<TAB>hash` with kind ∈ class, builtin, utility."
function generate_hashes(io::IO, api)
    for cls in api["classes"], m in get(cls, "methods", [])
        haskey(m, "hash") && println(io, "class\t$(cls["name"])\t$(m["name"])\t$(m["hash"])")
    end
    for b in api["builtin_classes"], m in get(b, "methods", [])
        println(io, "builtin\t$(b["name"])\t$(m["name"])\t$(m["hash"])")
    end
    for f in api["utility_functions"]
        println(io, "utility\t\t$(f["name"])\t$(f["hash"])")
    end
    return nothing
end
