# Generates generated/builtin_methods.jl: glue for the methods of the non-math builtins (String, StringName, NodePath,
# RID, Callable, Signal, Array, Dictionary, Packed*Array). Math builtins are hand-written (src/builtins/).

"`(julia receiver type, receiver kind)`; kinds: :temp (converted per call), :bits (isbits wrapper), :field (`raw` field)."
const BUILTIN_RECEIVERS = merge(
    Dict("String" => ("AbstractString", :temp), "StringName" => ("Symbol", :temp), "NodePath" => ("NodePath", :temp),
         "RID" => ("RID", :bits), "Callable" => ("Callable", :field), "Signal" => ("Signal", :field),
         "Array" => ("GDArray", :field), "Dictionary" => ("GDDictionary", :field)),
    Dict(p => (p, :field) for p in PACKED_TYPES))

const TEMP_RECEIVER = Dict("String" => "FFI.new_string(self)", "StringName" => "FFI.new_string_name(self)",
                           "NodePath" => "Internals.new_node_path(self)")

# Base functions that builtin methods may extend for our own receiver types (no conflicting Julia meaning).
const BUILTIN_BASE_ALLOWED = Set(["bind"])

function emit_builtin_method(io::IO, ctx::Context, type::AbstractString, m, fields)
    name = m["name"]
    recv, kind = BUILTIN_RECEIVERS[type]
    fname = method_function(ctx, name)
    if startswith(fname, "Base.") && !(name in BUILTIN_BASE_ALLOWED && kind != :temp)
        push!(ctx.renames, "builtin method not bound (Julia equivalent in Base): $type.$name")
        return false
    end
    params = method_params(ctx, type, m, fields)
    ret_type = get(m, "return_type", nothing)
    ret_spec = ret_type === nothing ? nothing : type_spec(ctx, ret_type)
    if params === nothing || (ret_type !== nothing && ret_spec === nothing)
        push!(ctx.skipped, "$type.$name (unsupported argument or return type)")
        return false
    end
    is_static = get(m, "is_static", false)
    self_decl = is_static ? "::Type{$(type == "StringName" ? "Symbol" : recv == "AbstractString" ? "String" : recv)}" : "self::$recv"
    if get(m, "is_vararg", false)
        decls = join([self_decl; param_decl.(params); "args..."], ", ")
        sig = "$fname($decls)"
        print(io, method_doc(ctx, type, m, fname, sig))
        fixed = join((p.name * ", " for p in params))
        conv = ret_type === nothing ? "nothing" : startswith(ret_type, "enum::") ? "$(enum_type_ref(ctx, ret_type))(__v)" : "__v"
        println(io, "function $sig\n    __v = Internals.builtin_varcall(self, $(repr(Symbol(name))), $(fixed)args...)\n    return $conv\nend\n")
        return true
    end
    decls = join([self_decl; param_decl.(params)], ", ")
    sig = "$fname($decls)"
    print(io, method_doc(ctx, type, m, fname, sig))
    println(io, "function $sig")
    println(io, "    __m = Internals.@builtin_method($(repr(type)), $(repr(Symbol(name))), $(m["hash"]))")
    owned = Tuple{String, String}[]
    args = String[]
    for (i, p) in enumerate(params)
        local_name = "__a$i"
        p.spec.owned ? push!(owned, (local_name, subst(p.spec.arg, p.name))) :
                       println(io, "    $local_name = $(subst(p.spec.arg, p.name))")
        push!(args, local_name)
    end
    base = is_static ? "C_NULL" : kind == :field ? "Internals.raw_ptr(self)" : "Base.unsafe_convert(Ptr{Cvoid}, __self)"
    preserve = is_static ? "" : kind == :field ? "self" : "__self"
    native_ret = ret_spec === nothing ? "Nothing" : ret_spec.native
    call = "FFI.builtin_ptrcall($native_ret, __m, $base" * join((", " * a for a in args)) * ")"
    isempty(preserve) || (call = "GC.@preserve $preserve $call")
    indent = "    "
    println(io, indent, "local __r")
    if !is_static && kind == :temp
        push!(owned, ("__self_raw", TEMP_RECEIVER[type]))
    end
    for (local_name, expr) in owned
        println(io, indent, "$local_name = $expr")
        println(io, indent, "try")
        indent *= "    "
    end
    if !is_static && kind == :temp
        println(io, indent, "__self = Ref(__self_raw)")
    elseif !is_static && kind == :bits
        println(io, indent, "__self = Ref(self.raw)")
    end
    println(io, indent, "__r = $call")
    for (local_name, _) in reverse(owned)
        indent = indent[1:(end - 4)]
        println(io, indent, "finally\n", indent, "    FFI.destroy!($local_name)\n", indent, "end")
    end
    println(io, "    return ", ret_spec === nothing ? "nothing" : subst(ret_spec.ret, "__r"))
    println(io, "end\n")
    return true
end

"Write glue for every method of the non-math builtins. Returns the generation context."
function generate_builtin_methods(io::IO, api; precision::AbstractString = "single")
    ctx = Context(api; scope = :core)
    fields = struct_fields(api, build_configuration(precision))
    println(io, "# GENERATED by GodotBindgen from extension_api.json ($(api["header"]["version_full_name"])). Do not edit.\n" * SOURCE_NOTICE)
    println(io, "# Methods of the non-math builtins; Julia idioms (AbstractVector, AbstractDict, ...) are hand-written.\n")
    fnames = Set{String}()
    bodies = IOBuffer()
    for b in api["builtin_classes"]
        haskey(BUILTIN_RECEIVERS, b["name"]) || continue
        for m in get(b, "methods", [])
            if emit_builtin_method(bodies, ctx, b["name"], m, fields)
                f = method_function(ctx, m["name"])
                startswith(f, "Base.") || push!(fnames, f)
            end
        end
    end
    for f in sort(collect(fnames))
        println(io, "function $f end")
    end
    println(io)
    write(io, take!(bodies))
    for chunk in Iterators.partition(sort(collect(fnames)), 50)
        println(io, "export " * join(chunk, ", "))
    end
    return ctx
end
