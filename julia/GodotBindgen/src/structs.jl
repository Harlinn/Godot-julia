# Generates generated/builtin_structs.jl: ABI layouts of the math builtins (methods are hand-written in phase 05).

const META_TYPES = Dict("float" => "Float32", "double" => "Float64", "int32" => "Int32")

# Godot stores Basis as rows while its API members x/y/z are the columns (C# keeps private rows the same way).
const ROW_FIELDS = Dict("Basis" => ["row0", "row1", "row2"])

"`name => [(field, julia_type)]` for every math builtin in the given build configuration."
function struct_fields(api, config::AbstractString)
    entry = find_configuration(api["builtin_class_member_offsets"], config)
    fields = Dict{String, Vector{Tuple{String, String}}}()
    for cls in entry["classes"]
        cls["name"] in MATH_BUILTINS || continue
        members = sort(cls["members"]; by = m -> m["offset"])
        names = get(ROW_FIELDS, cls["name"], [m["member"] for m in members])
        fields[cls["name"]] = [(n, get(META_TYPES, m["meta"], m["meta"])) for (n, m) in zip(names, members)]
    end
    return fields
end

function struct_order(fields)
    order = String[]
    visit(name) = begin
        (name in order || !haskey(fields, name)) && return
        foreach(f -> visit(f[2]), fields[name])
        push!(order, name)
    end
    foreach(visit, MATH_BUILTINS)
    return order
end

leaf_fields(fields, name) = haskey(fields, name) ?
    reduce(vcat, (leaf_fields(fields, t) for (_, t) in fields[name])) : [name]

function flatten_args(fields, name, args::Vector{String})
    haskey(fields, name) || return popfirst!(args)
    parts = [flatten_args(fields, t, args) for (_, t) in fields[name]]
    haskey(ROW_FIELDS, name) && pushfirst!(parts, "Internals.ROWS")
    return "$name(" * join(parts, ", ") * ")"
end

"Julia expression for a builtin constant's Godot literal (e.g. `Vector2(inf, inf)`), or `nothing`."
function builtin_constant(fields, type::AbstractString, value::AbstractString)
    m = match(r"^(\w+)\((.*)\)$", value)
    (m === nothing || m[1] != type) && return nothing
    args = [replace(strip(a), r"^(-?)inf$" => s"\1Inf") for a in split(m[2], ",")]
    all(a -> tryparse(Float64, a) !== nothing, args) || return nothing
    length(args) == length(leaf_fields(fields, type)) || return nothing
    if type == "Color"
        # Named colors are 8-bit values; build them exactly like Color::hex does.
        args = ["$(round(Int, parse(Float64, a) * 255))f0 / 255f0" for a in args]
    end
    return "$type($(join(args, ", ")))"
end

function emit_enum(io::IO, type_name::AbstractString, value_prefix::AbstractString, enum; doc = "")
    supertype = get(enum, "is_bitfield", false) ? "GodotBitfield" : "GodotEnum"
    isempty(doc) || print(io, docstring([doc]))
    println(io, "struct $type_name <: $supertype\n    value::Int64\nend")
    pairs = join(["(:$(value_prefix)$(v["name"]), $(v["value"]))" for v in enum["values"]], ", ")
    println(io, "Internals.enum_values(::Type{$type_name}) = ($pairs,)")
    for v in enum["values"]
        desc = get(v, "description", "")
        isempty(desc) || print(io, docstring([bbcode_to_markdown(desc)]))
        println(io, "const $(value_prefix)$(v["name"]) = $type_name($(v["value"]))")
    end
    println(io)
end

function generate_builtin_structs(io::IO, api, iface; precision::AbstractString = "single")
    fields = struct_fields(api, build_configuration(precision))
    consts = variant_type_constants(iface)
    builtins = Dict(b["name"] => b for b in api["builtin_classes"])
    println(io, "# GENERATED by GodotBindgen from extension_api.json. Do not edit.\n" * SOURCE_NOTICE)
    println(io, "# ABI layouts of Godot's math builtins; their methods are hand-written in src/builtins/.\n")
    order = struct_order(fields)
    for name in order
        b = builtins[name]
        doc = bbcode_to_markdown(get(b, "brief_description", ""))
        isempty(doc) || print(io, docstring([doc]))
        println(io, "struct $name")
        for (f, t) in fields[name]
            println(io, "    $f::$t")
        end
        if haskey(ROW_FIELDS, name)
            rows = join(("$f::$t" for (f, t) in fields[name]), ", ")
            println(io, "    # Rows (memory order); `$name(x, y, z)` (hand-written) takes the columns.")
            println(io, "    $name(::Internals.Rows, $rows) = new($(join(first.(fields[name]), ", ")))")
        end
        println(io, "end")
        println(io, "FFI.variant_type(::Type{$name}) = FFI.$(variant_type_constant(consts, name))")
        println(io, "Internals.to_variant(x::$name) = Internals.variant_from_bits(FFI.variant_type($name), x)")
        leaves = leaf_fields(fields, name)
        if length(leaves) != length(fields[name])
            args = ["a$i" for i in eachindex(leaves)]
            params = join(("$a::Real" for a in args), ", ")
            println(io, "$name($params) = $(flatten_args(fields, name, copy(args)))")
        end
        println(io)
    end
    println(io, "const MATH_TYPES = ($(join(order, ", ")),)\n")
    for b in api["builtin_classes"], e in get(b, "enums", [])
        emit_enum(io, "$(b["name"])_$(e["name"])", "$(b["name"])_", e)
    end
    constants = String[]
    for b in api["builtin_classes"]
        b["name"] in order || continue
        for c in get(b, "constants", [])
            expr = builtin_constant(fields, b["name"], c["value"])
            expr === nothing && error("cannot translate constant $(b["name"]).$(c["name"]) = $(c["value"])")
            desc = get(c, "description", "")
            isempty(desc) || print(io, docstring([bbcode_to_markdown(desc)]))
            println(io, "const $(b["name"])_$(c["name"]) = $expr")
            push!(constants, "$(b["name"])_$(c["name"])")
        end
    end
    exports = vcat(order, ["$(b["name"])_$(e["name"])" for b in api["builtin_classes"] for e in get(b, "enums", [])],
                   ["$(b["name"])_$(v["name"])" for b in api["builtin_classes"] for e in get(b, "enums", []) for v in e["values"]])
    println(io, "\nexport " * join(exports, ", "))
    for chunk in Iterators.partition(constants, 50)
        println(io, "export " * join(chunk, ", "))
    end
    return nothing
end
