# Generates julia/Godot/src/generated/interface.jl from gdextension_interface.json.

function docstring(lines, extra = String[])
    text = join(vcat(String.(lines), extra), "\n")
    isempty(strip(text)) && return ""
    escaped = replace(text, "\\" => "\\\\", "\$" => "\\\$", "\"\"\"" => "\\\"\\\"\\\"")
    return "\"\"\"\n$escaped\n\"\"\"\n"
end

function deprecation_note(entry)
    dep = get(entry, "deprecated", nothing)
    dep === nothing && return String[]
    note = "Deprecated since Godot $(dep["since"])"
    haskey(dep, "replace_with") && (note *= "; use `$(dep["replace_with"])` instead")
    haskey(dep, "message") && (note *= ". $(dep["message"])")
    return ["", "!!! warning", "    $note."]
end

function emit_types(io::IO, types, named)
    for t in types
        name = t["name"]
        kind = t["kind"]
        if kind == "enum"
            println(io, "const $name = Int32")
            for v in t["values"]
                println(io, "const $(v["name"]) = Int32($(v["value"]))")
            end
        elseif kind == "alias"
            println(io, "const $name = $(julia_ctype(t["type"], named))")
        elseif kind in ("handle", "function")
            println(io, "const $name = Ptr{Cvoid}")
        elseif kind == "struct"
            print(io, docstring(get(t, "description", String[])))
            println(io, "struct $name")
            for m in t["members"]
                println(io, "    $(safe_name(m["name"]))::$(julia_ctype(m["type"], named))")
            end
            println(io, "end")
        else
            error("unknown type kind $kind for $name")
        end
        println(io)
    end
end

function emit_table(io::IO, functions)
    println(io, "\"Function pointers resolved from `get_proc_address` (one field per GDExtension interface function).\"")
    println(io, "struct InterfaceTable")
    for f in functions
        println(io, "    $(f["name"])::Ptr{Cvoid}")
    end
    println(io, "end\n")
    println(io, "const INTERFACE = Ref{InterfaceTable}()\n")
    println(io, """
    \"\"\"
        load_interface!(get_proc_address) -> Vector{Symbol}

    Resolve every interface function. Returns the names Godot did not provide.
    \"\"\"
    function load_interface!(get_proc_address::Ptr{Cvoid})
        resolve(name) = ccall(get_proc_address, Ptr{Cvoid}, (Cstring,), name)
        pointers = Ptr{Cvoid}[resolve(String(name)) for name in fieldnames(InterfaceTable)]
        INTERFACE[] = InterfaceTable(pointers...)
        return Symbol[name for (name, p) in zip(fieldnames(InterfaceTable), pointers) if p == C_NULL]
    end
    """)
end

function emit_wrappers(io::IO, functions, named)
    for f in functions
        name = f["name"]
        args = get(f, "arguments", [])
        argnames = [safe_name(a["name"]) for a in args]
        argtypes = [julia_ctype(a["type"], named) for a in args]
        rettype = haskey(f, "return_value") ? julia_ctype(f["return_value"]["type"], named) : "Cvoid"
        sig = "$name(" * join(argnames, ", ") * ")"
        lines = ["    $sig -> $rettype", ""]
        append!(lines, String.(get(f, "description", String[])))
        for a in args
            desc = join(get(a, "description", String[]), " ")
            push!(lines, "- `$(safe_name(a["name"]))::$(a["type"])`" * (isempty(desc) ? "" : ": $desc"))
        end
        print(io, docstring(lines, deprecation_note(f)))
        tuple = isempty(argtypes) ? "()" : "(" * join(argtypes, ", ") * (length(argtypes) == 1 ? ",)" : ")")
        callargs = isempty(argnames) ? "" : ", " * join(argnames, ", ")
        println(io, "@inline $sig = ccall(INTERFACE[].$name, $rettype, $tuple$callargs)\n")
    end
end

function generate_interface(io::IO, iface)
    types = iface["types"]
    named = Set{String}(t["name"] for t in types)
    functions = iface["interface"]
    println(io, "# GENERATED by GodotBindgen from gdextension_interface.json (format $(iface["format_version"])). Do not edit.\n" * SOURCE_NOTICE * "\n")
    emit_types(io, types, named)
    emit_table(io, functions)
    emit_wrappers(io, functions, named)
    return nothing
end
