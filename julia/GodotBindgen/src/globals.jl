# Generates generated/global_enums.jl (global enums/constants) and generated/globals.jl (`GD` utility functions).

function emit_utility(io::IO, ctx::Context, f, fields)
    name = f["name"]
    params = Param[]
    for a in get(f, "arguments", [])
        spec = type_spec(ctx, a["type"])
        spec === nothing && (push!(ctx.skipped, "utility $name"); return)
        push!(params, Param(safe_arg(a["name"]), spec, nothing))
    end
    ret_type = get(f, "return_type", nothing)
    ret_spec = ret_type === nothing ? nothing : type_spec(ctx, ret_type)
    (ret_type !== nothing && ret_spec === nothing) && (push!(ctx.skipped, "utility $name"); return)
    fname = safe_arg(name)
    vararg = get(f, "is_vararg", false)
    decls = join([param_decl.(params); vararg ? ["args..."] : String[]], ", ")
    lines = ["    GD.$fname($decls)", ""]
    desc = get(f, "description", "")
    isempty(desc) || push!(lines, bbcode_to_markdown(desc))
    print(io, docstring(lines))
    fn = "Internals.@utility_function($(repr(Symbol(name))), $(f["hash"]))"
    native = ret_spec === nothing ? "Nothing" : ret_spec.native
    ret = ret_spec === nothing ? "nothing" : subst(ret_spec.ret, "__r")
    if vararg
        fixed = join(("Internals.to_variant($(p.name)), " for p in params))
        println(io, """
        function $fname($decls)
            __vs = FFI.RawVariant[$(fixed)(Internals.to_variant(a) for a in args)...]
            try
                __r = Internals.utility_varcall($native, $fn, __vs)
                return $ret
            finally
                foreach(FFI.destroy!, __vs)
            end
        end
        """)
        return
    end
    println(io, "function $fname($decls)")
    owned = Tuple{String, String}[]
    args = String[]
    for (i, p) in enumerate(params)
        local_name = "__a$i"
        p.spec.owned ? push!(owned, (local_name, subst(p.spec.arg, p.name))) :
                       println(io, "    $local_name = $(subst(p.spec.arg, p.name))")
        push!(args, local_name)
    end
    call = "FFI.utility_ptrcall($native, $fn" * join((", " * a for a in args)) * ")"
    indent = "    "
    isempty(owned) || println(io, indent, "local __r")
    for (local_name, expr) in owned
        println(io, indent, "$local_name = $expr")
        println(io, indent, "try")
        indent *= "    "
    end
    println(io, indent, "__r = $call")
    for (local_name, _) in reverse(owned)
        indent = indent[1:(end - 4)]
        println(io, indent, "finally\n", indent, "    FFI.destroy!($local_name)\n", indent, "end")
    end
    println(io, "    return $ret")
    println(io, "end\n")
end

function generate_global_enums(io::IO, api)
    println(io, "# GENERATED by GodotBindgen from extension_api.json. Do not edit.\n" * SOURCE_NOTICE * "\n")
    exports = String[]
    for e in api["global_enums"]
        T = replace(e["name"], "." => "")
        # Values already carry their enum prefix (KEY_*, TYPE_*, OP_*, ...), so they are not qualified further.
        emit_enum(io, T, "", e)
        push!(exports, T)
        append!(exports, [v["name"] for v in e["values"]])
    end
    for k in api["global_constants"]
        println(io, "const $(k["name"]) = $(k["value"])")
        push!(exports, k["name"])
    end
    for chunk in Iterators.partition(exports, 50)
        println(io, "export " * join(chunk, ", "))
    end
end

function generate_globals(io::IO, api, ctx::Context; precision::AbstractString = "single")
    fields = struct_fields(api, build_configuration(precision))
    println(io, "# GENERATED by GodotBindgen from extension_api.json. Do not edit.\n" * SOURCE_NOTICE)
    println(io, """

    \"\"\"
        GD

    Godot's global utility functions (`GD.print`, `GD.randf`, `GD.lerp`, ...), as in C#'s `GD` class.
    \"\"\"
    module GD
    using ..Godot
    using ..Godot: Internals, FFI
    """)
    for f in api["utility_functions"]
        emit_utility(io, ctx, f, fields)
    end
    println(io, "include(joinpath(@__DIR__, \"..\", \"core\", \"gd.jl\"))")
    println(io, "end # module GD\nexport GD")
end
